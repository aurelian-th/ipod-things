"""Rockbox's 2048 tile strip (a 24-bit BMP, 18 tiles of 48 x 48 from 131072
down to the empty cell) as a C array of RGB565 tiles in ascending order:
tiles[0] is the empty cell, tiles[n] shows 2**n."""

import struct
import sys

SIDE = 48


def main(source, target):
    data = open(source, "rb").read()
    offset = struct.unpack_from("<I", data, 10)[0]
    width, height = struct.unpack_from("<ii", data, 18)
    if struct.unpack_from("<H", data, 28)[0] != 24 or height != SIDE or width % SIDE:
        sys.exit(f"{source}: expected a 24-bit strip of {SIDE} x {SIDE} tiles")
    count = width // SIDE
    stride = (width * 3 + 3) & ~3
    rows = []
    for y in range(height):  # BMP rows are stored bottom-up
        base = offset + (height - 1 - y) * stride
        rows.append(data[base : base + width * 3])

    def pixel(x, y):
        b, g, r = rows[y][x * 3 : x * 3 + 3]
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

    with open(target, "w") as out:
        out.write("/* SPDX-License-Identifier: GPL-2.0-or-later */\n")
        out.write(
            "/* Generated by tiles.py from Rockbox's 2048 tiles.\n"
            " * Copyright (C) 2014 Franklin Wei. */\n"
        )
        out.write("#include <stdint.h>\n\n")
        out.write(f"const unsigned tile_count = {count};\n")
        out.write(f"const uint16_t tiles[{count}][{SIDE} * {SIDE}] = {{\n")
        for index in range(count):
            left = (count - 1 - index) * SIDE
            out.write("    {")
            words = [pixel(left + x, y) for y in range(SIDE) for x in range(SIDE)]
            for i in range(0, len(words), 12):
                out.write(
                    "\n        "
                    + ", ".join(f"0x{w:04x}" for w in words[i : i + 12])
                    + ","
                )
            out.write("\n    },\n")
        out.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
